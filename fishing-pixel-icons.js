  const CACHE = Object.create(null);

  function compileBody(name) {
    if (CACHE[name]) return CACHE[name];
    const grid = SPRITES[name] || SPRITES.fish;
    let rects = "";
    for (let y = 0; y < 16; y++) {
      const row = grid[y] || "................";
      let x = 0;
      while (x < 16) {
        const ch = row[x];
        if (!ch || ch === "." || !PALETTE[ch]) {
          x++;
          continue;
        }
        let w = 1;
        while (x + w < 16 && row[x + w] === ch) w++;
        rects += `<rect x="${x}" y="${y}" width="${w}" height="1" fill="${PALETTE[ch]}"/>`;
        x += w;
      }
    }
    CACHE[name] = rects;
    return rects;
  }

